################################################################################
# Upper West Region EMOD Malaria Model
#
# AIM 1:
# Adapt and calibrate the EMOD malaria transmission model to the
# Upper West Region of Ghana.
#
# --------------------------------------------------------------------------
# BURN-IN EXPERIMENT
# --------------------------------------------------------------------------
#
#   1963 ------------------------------- 2012
#          50-year transmission burn-in
#                                           |  serialized state
#                                           v
#                                        2013
#                                pickup / calibration begins
#
# The burn-in uses the tiled 365-day climatology generated by
# build_weather_upperWest.py, at:
#
#     /shared/home/grace/Final-Project-UWR/climate/burnin
#
# Day-count convention: the climatology has exactly 18,250 days
# (50 x 365, no leap days), so Simulation_Duration is that flat count.
#
# The model is configured as a single Upper West Region node.
#
# --------------------------------------------------------------------------
# BURN-IN CONTENT
# --------------------------------------------------------------------------
#
# INCLUDED:
#   - 50-year tiled climatology
#   - Larval habitat parameter sweep
#   - Historical case management (phase == "burnin" rows of
#     intervention_CMBN.csv), so the serialized state carries the
#     pre-2013 treatment-seeking history into the pickup
#
# NOT INCLUDED:
#   - IRS
#   - IG2
#   - SMC
#   - Historical ITN campaigns
#
# CASE-MANAGEMENT DAY ALIGNMENT:
#
# The CSV's burn-in rows say year=2009 but start_day=16425, which is
# (2008-1963)*365, i.e. the start of 2008 on this calendar. The two
# disagree by one year. CM_DAY_SOURCE below chooses which one wins:
#   "year" -> start_day = (year - 1963) * 365 + 1   (2009 -> day 16791)
#   "csv"  -> use the CSV start_day as-is            (day 16425)
# Duration is clipped either way so nothing runs past BURNIN_DAYS.
# The pickup script must do its own alignment against a 2013 start.
#
# CASE-MANAGEMENT COVERAGE:
#
# This emodpy_malaria version removed the 'seek' target parameter, so
# coverage x seek is folded into Demographic_Coverage below.
#
# The CSV also contains stray whitespace (e.g. "AL  ", "3651 ", "0.60  ");
# every field is stripped and numeric columns are parsed explicitly.
#
# Experiment size: 5 xTLH x 20 habitat x 5 seeds = 500 simulations.
